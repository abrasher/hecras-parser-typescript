import { describe, expect, it } from "vitest"
import { parseRiverReachData } from "../../../src/parsers/geometry/riverReachParser"

describe.skip("River Reach Cross-Section Data Unit Tests", () => {
  const lines = completeXSTestString.split("\n")

  it("should parse complete cross-section with station/elevation data", () => {
    const riverReachData = parseRiverReachData(lines[0], lines, 0)
    const crossSection = riverReachData.data.crossSections[0]

    expect(crossSection).toBeDefined()
    expect(crossSection.type).toBe(1)
    expect(crossSection.riverMile).toBe("658")
    expect(crossSection.stationElevationCount).toBe(355)
    expect(crossSection.stationElevationPoints).toHaveLength(355)

    // Check first few station/elevation points
    expect(crossSection.stationElevationPoints[0]).toEqual({ station: 0, elevation: 266.05 })
    expect(crossSection.stationElevationPoints[1]).toEqual({ station: 1, elevation: 266.08 })
    expect(crossSection.stationElevationPoints[2]).toEqual({ station: 2, elevation: 266.04 })
  })

  it("should parse Manning's n values", () => {
    const riverReachData = parseRiverReachData(lines[0], lines, 0)
    const crossSection = riverReachData.data.crossSections[0]

    expect(crossSection.manningCount).toBe(12)
    expect(crossSection.manningValues).toHaveLength(12)

    // Check first Manning segment
    expect(crossSection.manningValues![0]).toEqual({
      station: 0,
      nValue: 0.015,
      unknownParameter: 0,
    })
  })

  it("should parse ineffective flow areas", () => {
    const riverReachData = parseRiverReachData(lines[0], lines, 0)
    const crossSection = riverReachData.data.crossSections[0]

    expect(crossSection.ineffectiveCount).toBe(2)
    expect(crossSection.ineffectiveFlowAreas).toHaveLength(2)
  })

  it("should parse bank stations and other properties", () => {
    const riverReachData = parseRiverReachData(lines[0], lines, 0)
    const crossSection = riverReachData.data.crossSections[0]

    expect(crossSection.leftBankStation).toBe(689.93)
    expect(crossSection.rightBankStation).toBe(693.28)
    expect(crossSection.expansionContractionCoefficients).toEqual({
      expansion: 0.3,
      contraction: 0.1,
    })
  })
})

